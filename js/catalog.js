function showItemInfo(key, ev) {
  if (ev) {
    ev.preventDefault();
    ev.stopPropagation();
  }
  const info = ITEM_INFO[key];
  if (!info) return;
  const price = DB[key];
  const numLabel = String(key).replace("_", ".");
  document.getElementById("info-modal-num").textContent = "п. " + numLabel;
  document.getElementById("info-modal-text").textContent = info.text;
  document.getElementById("info-modal-unit-val").textContent = info.unit || "—";
  document.getElementById("info-modal-price-val").textContent =
    price != null ? formatSum(price) + " грн" : "—";
  document.getElementById("info-modal-overlay").classList.add("open");
}
function closeItemInfo(ev) {
  if (ev && ev.target !== ev.currentTarget) return;
  document.getElementById("info-modal-overlay").classList.remove("open");
}

// ── HOVER TOOLTIP (коротка підказка при наведенні на ℹ) ──────────────
function resolveTooltipKey(el) {
  const oc = el.getAttribute("onclick") || "";
  let m = oc.match(/showItemInfo\('([^']+)'/);
  if (m) return m[1];
  m = oc.match(/getWinTypeItemKey\((\d+)\)/);
  if (m) return getWinTypeItemKey(m[1]);
  m = oc.match(/getElementById\('s-type-(\d+)'\)/);
  if (m) return document.getElementById("s-type-" + m[1])?.value;
  return null;
}
function buildTooltipHTML(key) {
  const info = ITEM_INFO[key];
  if (!info) return "";
  const price = DB[key];
  const numLabel = String(key).replace("_", ".");
  let desc = info.text;
  if (desc.length > 140) desc = desc.slice(0, 140).trim() + "…";
  return `<div class="item-tooltip-num">п. ${numLabel}</div><div class="item-tooltip-text">${desc}</div><div class="item-tooltip-meta">${info.unit} · <b>${price != null ? formatSum(price) + " грн" : "—"}</b></div>`;
}
function positionTooltip(tip, btn) {
  const r = btn.getBoundingClientRect();
  const tw = 260;
  let left = r.left;
  let top = r.bottom + 6;
  if (left + tw > window.innerWidth - 10) left = window.innerWidth - tw - 10;
  if (top + 100 > window.innerHeight - 10) top = r.top - 100;
  tip.style.left = Math.max(8, left) + "px";
  tip.style.top = Math.max(8, top) + "px";
}
function showTooltipFor(btn) {
  const key = resolveTooltipKey(btn);
  if (!key || !ITEM_INFO[key]) return;
  const tip = document.getElementById("item-tooltip");
  tip.innerHTML = buildTooltipHTML(key);
  tip.classList.add("show");
  positionTooltip(tip, btn);
}
function hideItemTooltip() {
  const tip = document.getElementById("item-tooltip");
  if (tip) tip.classList.remove("show");
}
document.addEventListener("mouseover", function (e) {
  const btn = e.target.closest && e.target.closest(".item-info-btn");
  if (btn) showTooltipFor(btn);
});
document.addEventListener("mouseout", function (e) {
  const btn = e.target.closest && e.target.closest(".item-info-btn");
  if (btn && !btn.contains(e.relatedTarget)) hideItemTooltip();
});
